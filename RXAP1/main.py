from cpu import Z80
from memory import Memory


# ==========================================
# CREATE CPU
# ==========================================

memory = Memory()
cpu = Z80(memory)

cpu.reset()


# ==========================================
# CB INSTRUCTION TEST
# ==========================================

program = [

    # --------------------------------------
    # A = 00000001
    # --------------------------------------

    0x3E, 0x01,

    # RLC A
    # 00000001 -> 00000010
    0xCB, 0x07,

    # --------------------------------------
    # RRC A
    # 00000010 -> 00000001
    # --------------------------------------

    0xCB, 0x0F,

    # --------------------------------------
    # SET bit 7,A
    # 00000001 -> 10000001
    # --------------------------------------

    0xCB, 0xFF,

    # --------------------------------------
    # RES bit 7,A
    # 10000001 -> 00000001
    # --------------------------------------

    0xCB, 0xBF,

    # --------------------------------------
    # SET bit 3,A
    # 00000001 -> 00001001
    # --------------------------------------

    0xCB, 0xDF,

    # --------------------------------------
    # BIT 3,A
    # Should find bit 3 = 1
    # --------------------------------------

    0xCB, 0x5F,

    # --------------------------------------
    # SRL A
    # 00001001 -> 00000100
    # --------------------------------------

    0xCB, 0x3F,

    # --------------------------------------
    # SLA A
    # 00000100 -> 00001000
    # --------------------------------------

    0xCB, 0x27,

    # HALT
    0x76
]


# ==========================================
# LOAD PROGRAM
# ==========================================

memory.load(
    program,
    0x0000
)


# ==========================================
# RUN
# ==========================================

print("=" * 45)
print("          Z80 CB DECODER TEST")
print("=" * 45)
print()

cpu.run()


# ==========================================
# RESULTS
# ==========================================

print()
print("CPU HALTED")
print()

print("A  =", hex(cpu.a))
print("F  =", hex(cpu.f))
print("PC =", hex(cpu.pc))

print()
print("Binary A:")

print(
    format(
        cpu.a,
        "08b"
    )
)

print()
print("=" * 45)